"""Generate Rust tables reproducing CPython 3.13 str semantics used by IRRd v4."""
import re
import sys
import unicodedata

MAX = sys.maxunicode + 1


def ranges(pred):
    out = []
    start = None
    for cp in range(MAX):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def is_char(cp):
    return not (0xD800 <= cp <= 0xDFFF)


def rs_str(s):
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in s) + '"'


lines = []
w = lines.append
w("// @generated by parity tooling from CPython " + sys.version.split()[0] + ", Unicode " + unicodedata.unidata_version + ".")
w("// Do not edit by hand. Regenerate with the v4 container's Python.")
w("")
w("/// Inclusive codepoint ranges for which `str.isprintable()` is false.")
r = ranges(lambda cp: not chr(cp).isprintable())
w(f"pub(crate) static NOT_PRINTABLE: [(u32, u32); {len(r)}] = [")
for a, b in r:
    w(f"    (0x{a:x}, 0x{b:x}),")
w("];")
w("")
# decimal digits: runs of consecutive codepoints with consecutive values
runs = []
cur = None
for cp in range(MAX):
    if not is_char(cp):
        continue
    c = chr(cp)
    if c.isdecimal():
        v = unicodedata.decimal(c)
        if cur and cur[1] == cp - 1 and cur[3] == v - 1:
            cur[1] = cp
            cur[3] = v
        else:
            if cur:
                runs.append(tuple(cur))
            cur = [cp, cp, v, v]
    # sanity: re \d equals isdecimal
    assert bool(re.match(r"\d", c)) == c.isdecimal(), cp
if cur:
    runs.append(tuple(cur))
w("/// Runs of decimal digits (`str.isdecimal()`, also `re` `\\d`): (first, last, value of first).")
w(f"pub(crate) static DECIMAL_RUNS: [(u32, u32, u8); {len(runs)}] = [")
for a, b, v, _ in runs:
    w(f"    (0x{a:x}, 0x{b:x}, {v}),")
w("];")
w("")
ws = [cp for cp in range(MAX) if is_char(cp) and chr(cp).isspace()]
w("/// Codepoints for which `str.isspace()` is true.")
w(f"pub(crate) static SPACES: [u32; {len(ws)}] = [" + ", ".join(f"0x{c:x}" for c in ws) + "];")
w("")
up = [(cp, chr(cp).upper()) for cp in range(MAX) if is_char(cp) and chr(cp).upper() != chr(cp)]
w("/// `str.upper()` for every codepoint it changes.")
w(f"pub(crate) static UPPER: [(u32, &str); {len(up)}] = [")
for cp, s in up:
    w(f"    (0x{cp:x}, {rs_str(s)}),")
w("];")
w("")
lo = [(cp, chr(cp).lower()) for cp in range(MAX) if is_char(cp) and chr(cp).lower() != chr(cp)]
w("/// `str.lower()` for every codepoint it changes (context free; final sigma handled in code).")
w(f"pub(crate) static LOWER: [(u32, &str); {len(lo)}] = [")
for cp, s in lo:
    w(f"    (0x{cp:x}, {rs_str(s)}),")
w("];")
w("")


def nonascii_matches(pattern):
    rx = re.compile(pattern, re.IGNORECASE)
    return [cp for cp in range(128, MAX) if is_char(cp) and rx.fullmatch(chr(cp))]


for name, pat in [
    ("IGNORECASE_A_Z", r"[A-Z]"),
    ("IGNORECASE_A_F", r"[A-F]"),
    ("IGNORECASE_UPPER_A_LOWER_F", r"[A-f]"),
]:
    m = nonascii_matches(pat)
    w(f"/// Non-ASCII codepoints matched by `{pat}` under `re.IGNORECASE`.")
    w(f"pub(crate) static {name}: [u32; {len(m)}] = [" + ", ".join(f"0x{c:x}" for c in m) + "];")
    w("")

sys.stdout.write("\n".join(lines))
