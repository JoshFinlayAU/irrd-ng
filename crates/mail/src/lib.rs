//! Outgoing mail, as v4's `send_email` (`irrd/utils/email.py`) sends it.
//!
//! v4 builds a `MIMEText` message and hands it to `smtplib.SMTP(email.smtp)`.
//! The message is rendered here the way Python's `email` package renders it
//! with the default `compat32` policy, so the bytes on the wire are the same:
//! the header order `MIMEText` produces, `us-ascii` and 7bit for ASCII
//! bodies, `utf-8` and base64 otherwise, `>From ` mangling and folding of
//! long headers. Delivery is plain SMTP through lettre, as `smtplib` does it
//! without `starttls()`.

#![deny(unsafe_code)]

pub mod messages;

use std::net::{IpAddr, SocketAddr, ToSocketAddrs};
use std::time::Duration;

/// v4's logger for mail.
pub const LOG_TARGET: &str = "irrd.utils.email";

/// The IRRd version v4 names in the footer it appends.
pub const IRRD_VERSION: &str = "4.5.4";

/// The `email.*` settings `send_email` reads.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct MailSettings {
    /// `email.from`
    pub from: Option<String>,
    /// `email.smtp`: `host`, `host:port` or an IPv6 literal.
    pub smtp: Option<String>,
    /// `email.footer` (`''` by default).
    pub footer: String,
    /// `email.recipient_override`
    pub recipient_override: Option<String>,
}

/// Why a mail was not sent. `Display` is what v4 logs as `{e}`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum MailError {
    /// The recipient check failed; v4 logs it and returns without raising.
    BadRecipient,
    /// Delivery failed: the text of the Python exception.
    Delivery(String),
}

impl std::fmt::Display for MailError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            MailError::BadRecipient => f.write_str("bad recipient"),
            MailError::Delivery(m) => f.write_str(m),
        }
    }
}

/// `socket.gethostname()`.
pub fn hostname() -> String {
    std::fs::read_to_string("/proc/sys/kernel/hostname")
        .map(|h| h.trim_end_matches('\n').to_owned())
        .unwrap_or_else(|_| "localhost".to_owned())
}

/// `email.utils.parseaddr(addr)[1]`, for the shapes that occur in RPSL
/// `e-mail`, `mnt-nfy` and `email.*` values: a bare address, or a display
/// name with the address in angle brackets.
pub fn parseaddr(addr: &str) -> String {
    let a = addr.trim();
    if let (Some(open), Some(close)) = (a.rfind('<'), a.rfind('>'))
        && open < close
    {
        return a[open + 1..close].trim().to_owned();
    }
    // A bare address ends at the first whitespace or comment.
    a.split(|c: char| c.is_whitespace() || c == '(')
        .next()
        .unwrap_or_default()
        .to_owned()
}

/// What `send_email(recipient, subject, body)` would send: the envelope and
/// the message bytes. `None` when v4 refuses the recipient (and logs).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Rendered {
    /// The envelope sender (`From`'s address).
    pub envelope_from: String,
    /// The envelope recipient (`To`'s address).
    pub envelope_to: String,
    /// The message, CRLF line endings, as `smtplib` transmits it.
    pub bytes: Vec<u8>,
    /// The normalised subject, for the debug log.
    pub subject: String,
    /// The recipient after `recipient_override`.
    pub recipient: String,
}

/// Render a message as v4's `send_email` does, without sending it.
pub fn render(
    settings: &MailSettings,
    recipient: &str,
    subject: &str,
    body: &str,
    hostname: &str,
) -> Option<Rendered> {
    let recipient = settings
        .recipient_override
        .clone()
        .filter(|r| !r.is_empty())
        .unwrap_or_else(|| recipient.to_owned());
    let address = parseaddr(&recipient);
    if address.is_empty() || recipient.contains(['\r', '\n']) {
        tracing::error!(target: LOG_TARGET, "{}", messages::bad_recipient(subject, &recipient));
        return None;
    }
    let subject = subject.split_whitespace().collect::<Vec<_>>().join(" ");
    let mut full_body = body.to_owned();
    full_body.push('\n');
    full_body.push_str(&settings.footer);
    full_body.push_str(&format!(
        "\n\nGenerated by IRRd version {IRRD_VERSION} on {hostname}"
    ));
    let from = settings.from.clone().unwrap_or_default();

    let ascii = full_body.is_ascii();
    let mut out = String::new();
    let crlf = "\r\n";
    if ascii {
        out.push_str("Content-Type: text/plain; charset=\"us-ascii\"\r\n");
        out.push_str("MIME-Version: 1.0\r\n");
        out.push_str("Content-Transfer-Encoding: 7bit\r\n");
    } else {
        out.push_str("Content-Type: text/plain; charset=\"utf-8\"\r\n");
        out.push_str("MIME-Version: 1.0\r\n");
        out.push_str("Content-Transfer-Encoding: base64\r\n");
    }
    out.push_str(&fold_header("Subject", &subject));
    out.push_str(&fold_header("From", &from));
    out.push_str(&fold_header("To", &recipient));
    out.push_str(crlf);
    if ascii {
        out.push_str(&body_lines(&full_body));
    } else {
        out.push_str(&base64_body(full_body.as_bytes()));
    }
    Some(Rendered {
        envelope_from: parseaddr(&from),
        envelope_to: address,
        bytes: out.into_bytes(),
        subject,
        recipient,
    })
}

/// The payload with CRLF line endings and compat32's `>From ` mangling.
fn body_lines(body: &str) -> String {
    let mut out = String::with_capacity(body.len() + body.len() / 40);
    for (i, line) in body.split('\n').enumerate() {
        if i > 0 {
            out.push_str("\r\n");
        }
        let line = line.strip_suffix('\r').unwrap_or(line);
        if line.starts_with("From ") {
            out.push('>');
        }
        out.push_str(line);
    }
    out
}

const B64: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

fn base64(data: &[u8]) -> String {
    let mut out = String::with_capacity(data.len().div_ceil(3) * 4);
    for chunk in data.chunks(3) {
        let b = [
            chunk[0],
            chunk.get(1).copied().unwrap_or(0),
            chunk.get(2).copied().unwrap_or(0),
        ];
        let n = (u32::from(b[0]) << 16) | (u32::from(b[1]) << 8) | u32::from(b[2]);
        out.push(B64[(n >> 18) as usize & 63] as char);
        out.push(B64[(n >> 12) as usize & 63] as char);
        out.push(if chunk.len() > 1 {
            B64[(n >> 6) as usize & 63] as char
        } else {
            '='
        });
        out.push(if chunk.len() > 2 {
            B64[n as usize & 63] as char
        } else {
            '='
        });
    }
    out
}

/// `email.base64mime.body_encode(data)`: lines of 76 characters, each
/// ending in a newline (CRLF on the wire).
fn base64_body(data: &[u8]) -> String {
    let mut out = String::new();
    // 57 input bytes make one 76 character line.
    for chunk in data.chunks(57) {
        out.push_str(&base64(chunk));
        out.push_str("\r\n");
    }
    out
}

/// compat32's `_fold(name, value)`: `Header(value).encode(maxlinelen=78)`,
/// ported from `email.header._ValueFormatter` for ASCII values. A value
/// that is not ASCII becomes one RFC 2047 encoded word in utf-8, quoted
/// printable or base64, whichever is shorter, as `Charset.header_encode`
/// picks.
fn fold_header(name: &str, value: &str) -> String {
    let mut out = format!("{name}: ");
    if value.is_ascii() {
        out.push_str(&ascii_fold(name.len() + 2, value, 78));
    } else {
        let bytes = value.as_bytes();
        let b = base64(bytes);
        let q = q_encode(bytes);
        if q.len() < b.len() {
            out.push_str(&format!("=?utf-8?q?{q}?="));
        } else {
            out.push_str(&format!("=?utf-8?b?{b}?="));
        }
    }
    out.push_str("\r\n");
    out
}

/// `email.quoprimime.header_encode` without the charset wrapper.
fn q_encode(bytes: &[u8]) -> String {
    let mut out = String::new();
    for &b in bytes {
        match b {
            b' ' => out.push('_'),
            b'a'..=b'z' | b'A'..=b'Z' | b'0'..=b'9' | b'-' | b'!' | b'*' | b'+' | b'/' => {
                out.push(b as char)
            }
            _ => out.push_str(&format!("={b:02X}")),
        }
    }
    out
}

/// `_ValueFormatter.feed()` for an ASCII value, then `_str()`, with
/// `splitchars` `;, \t`.
fn ascii_fold(headerlen: usize, value: &str, maxlen: usize) -> String {
    // (fws, part) pairs, as `_ascii_split` makes them.
    let mut pairs: Vec<(String, String)> = Vec::new();
    {
        let mut fws = String::new();
        let mut part = String::new();
        let mut in_ws = false;
        for c in value.chars() {
            let ws = c == ' ' || c == '\t';
            if ws {
                if !in_ws {
                    pairs.push((std::mem::take(&mut fws), std::mem::take(&mut part)));
                    in_ws = true;
                }
                fws.push(c);
            } else {
                in_ws = false;
                part.push(c);
            }
        }
        pairs.push((fws, part));
    }
    let splitchars = [';', ',', ' ', '\t'];
    let mut lines: Vec<String> = Vec::new();
    let mut cur: Vec<(String, String)> = Vec::new();
    let mut initial = headerlen;
    let len_of = |c: &[(String, String)], initial: usize| {
        c.iter().map(|(f, p)| f.len() + p.len()).sum::<usize>() + initial
    };
    let line_str =
        |c: &[(String, String)]| c.iter().map(|(f, p)| format!("{f}{p}")).collect::<String>();
    for (fws, part) in pairs {
        cur.push((fws, part));
        if len_of(&cur, initial) <= maxlen {
            continue;
        }
        let mut split_at = None;
        'outer: for ch in splitchars {
            for i in (1..cur.len()).rev() {
                if ch == ' ' || ch == '\t' {
                    let f = &cur[i].0;
                    if f.starts_with(ch) {
                        split_at = Some(i);
                        break 'outer;
                    }
                }
                let prev = &cur[i - 1].1;
                if prev.ends_with(ch) {
                    split_at = Some(i);
                    break 'outer;
                }
            }
        }
        match split_at {
            Some(i) => {
                let remainder = cur.split_off(i);
                lines.push(line_str(&cur));
                cur = remainder;
                initial = 0;
            }
            None => {
                let (mut fws, part) = cur.pop().unwrap_or_default();
                if initial > 0 {
                    // newline(): the header gets a line to itself.
                    if len_of(&cur, initial) > 0 {
                        lines.push(line_str(&cur));
                    }
                    cur.clear();
                    initial = 0;
                    if fws.is_empty() {
                        fws = " ".to_owned();
                    }
                }
                cur.push((fws, part));
            }
        }
    }
    // _str(): newline() then join.
    if len_of(&cur, initial) > 0 {
        let only_ws = cur.iter().all(|(_, p)| p.is_empty());
        if only_ws && !lines.is_empty() {
            let s = line_str(&cur);
            if let Some(last) = lines.last_mut() {
                last.push_str(&s);
            }
        } else {
            lines.push(line_str(&cur));
        }
    }
    lines.join("\r\n")
}

/// `smtplib.SMTP(host)`: `host:port` is split when the host has exactly
/// one colon; the port defaults to 25.
pub fn smtp_target(smtp: &str) -> Result<(String, u16), MailError> {
    if smtp.matches(':').count() == 1
        && let Some((h, p)) = smtp.rsplit_once(':')
    {
        let port = p
            .parse::<u16>()
            .map_err(|_| MailError::Delivery(messages::NONNUMERIC_PORT.to_owned()))?;
        return Ok((h.to_owned(), port));
    }
    Ok((smtp.to_owned(), 25))
}

fn resolve(host: &str, port: u16) -> Result<SocketAddr, MailError> {
    let bare = host
        .strip_prefix('[')
        .and_then(|h| h.strip_suffix(']'))
        .unwrap_or(host);
    if let Ok(ip) = bare.parse::<IpAddr>() {
        return Ok(SocketAddr::new(ip, port));
    }
    (host, port)
        .to_socket_addrs()
        .map_err(|e| MailError::Delivery(messages::gaierror(&e)))?
        .next()
        .ok_or_else(|| MailError::Delivery(messages::GAI_NONAME.to_owned()))
}

/// `send_email(recipient, subject, body)`: render and deliver over SMTP.
/// Blocking; call it from a blocking context.
pub fn send_email(
    settings: &MailSettings,
    recipient: &str,
    subject: &str,
    body: &str,
) -> Result<(), MailError> {
    let Some(r) = render(settings, recipient, subject, body, &hostname()) else {
        return Err(MailError::BadRecipient);
    };
    tracing::debug!(target: LOG_TARGET, "{}", messages::sending(&r.recipient, &r.subject));
    deliver(settings, &r)
}

/// Deliver a rendered message.
pub fn deliver(settings: &MailSettings, r: &Rendered) -> Result<(), MailError> {
    use lettre::Transport;
    use lettre::address::Envelope;
    let smtp = settings.smtp.clone().unwrap_or_default();
    let (host, port) = smtp_target(&smtp)?;
    let addr = resolve(&host, port)?;
    let parse = |a: &str| {
        a.parse::<lettre::Address>()
            .map_err(|e| MailError::Delivery(e.to_string()))
    };
    let envelope = Envelope::new(Some(parse(&r.envelope_from)?), vec![parse(&r.envelope_to)?])
        .map_err(|e| MailError::Delivery(e.to_string()))?;
    let transport = lettre::SmtpTransport::builder_dangerous(addr.ip().to_string())
        .port(addr.port())
        .timeout(Some(Duration::from_secs(60)))
        .build();
    transport
        .send_raw(&envelope, &r.bytes)
        .map(|_| ())
        .map_err(|e| MailError::Delivery(e.to_string()))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn settings() -> MailSettings {
        MailSettings {
            from: Some("irrd@example.net".into()),
            smtp: Some("localhost:1025".into()),
            footer: "footer".into(),
            recipient_override: None,
        }
    }

    // Rendered by Python 3.13's email package in the v4 image:
    // MIMEText(body); msg["Subject"]; msg["From"]; msg["To"];
    // BytesGenerator(...).flatten(msg, linesep="\r\n").
    #[test]
    fn ascii_message() {
        let r = render(
            &settings(),
            "a@example.com",
            "subj  x\n y",
            "line\nFrom here\n",
            "host",
        )
        .expect("rendered");
        assert_eq!(
            String::from_utf8(r.bytes).expect("utf8"),
            "Content-Type: text/plain; charset=\"us-ascii\"\r\nMIME-Version: 1.0\r\n\
             Content-Transfer-Encoding: 7bit\r\nSubject: subj x y\r\nFrom: irrd@example.net\r\n\
             To: a@example.com\r\n\r\nline\r\n>From here\r\n\r\nfooter\r\n\r\n\
             Generated by IRRd version 4.5.4 on host"
        );
        assert_eq!(r.envelope_to, "a@example.com");
    }

    #[test]
    fn override_and_bad_recipient() {
        let mut s = settings();
        s.recipient_override = Some("o@example.com".into());
        let r = render(&s, "a@example.com", "s", "b", "h").expect("rendered");
        assert_eq!(r.envelope_to, "o@example.com");
        assert!(render(&settings(), "a@example.com\nBcc: x@y", "s", "b", "h").is_none());
        assert!(render(&settings(), "", "s", "b", "h").is_none());
    }

    #[test]
    fn long_subject_folds_at_spaces() {
        let subject = "route(6) objects in AAAAAAAAAA, BBBBBBBBBB, CCCCCCCCCC, DDDDDDDDDD marked RPKI invalid";
        let h = fold_header("Subject", subject);
        assert_eq!(
            h,
            "Subject: route(6) objects in AAAAAAAAAA, BBBBBBBBBB, CCCCCCCCCC,\r\n DDDDDDDDDD marked RPKI invalid\r\n"
        );
    }

    // More cases from the same oracle.
    #[test]
    fn folding_like_python() {
        let long = "a".repeat(114);
        assert_eq!(
            fold_header("Subject", &format!("{long} b c")),
            format!("Subject: \r\n {long}\r\n b c\r\n")
        );
        assert_eq!(
            fold_header(
                "Subject",
                "one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen"
            ),
            "Subject: one two three four five six seven eight nine ten eleven twelve\r\n thirteen fourteen fifteen sixteen seventeen\r\n"
        );
        assert_eq!(fold_header("Subject", "a;b,c d"), "Subject: a;b,c d\r\n");
        assert_eq!(
            fold_header("Subject", "B\u{f6}ing route objects \u{e4}"),
            "Subject: =?utf-8?q?B=C3=B6ing_route_objects_=C3=A4?=\r\n"
        );
    }

    #[test]
    fn utf8_body_is_base64() {
        let r = render(
            &MailSettings {
                footer: String::new(),
                ..settings()
            },
            "a@example.com",
            "s",
            &format!("B\u{f6}dy \u{e4}\nline two\n{}", "x".repeat(100)),
            "h",
        )
        .expect("rendered");
        let text = String::from_utf8(r.bytes).expect("utf8");
        assert!(text.starts_with("Content-Type: text/plain; charset=\"utf-8\"\r\nMIME-Version: 1.0\r\nContent-Transfer-Encoding: base64\r\n"));
    }

    #[test]
    fn smtp_host_port() {
        assert_eq!(
            smtp_target("mail:1025").expect("ok"),
            ("mail".to_owned(), 1025)
        );
        assert_eq!(smtp_target("mail").expect("ok"), ("mail".to_owned(), 25));
        assert_eq!(smtp_target("::1").expect("ok"), ("::1".to_owned(), 25));
        assert!(smtp_target("mail:x").is_err());
    }

    #[test]
    fn base64_lines() {
        assert_eq!(base64(b"Ma"), "TWE=");
        assert_eq!(base64(b"M"), "TQ==");
        assert_eq!(base64(b"Man"), "TWFu");
        let body = base64_body(&[b'a'; 60]);
        let lines: Vec<&str> = body.split("\r\n").collect();
        assert_eq!(lines[0].len(), 76);
    }
}
