#!/usr/bin/env python3
"""Build the load bench query mix from corpus bindings.

    mix.py --bindings bindings.json --expand HOST:PORT [--sets N] > mix.tsv

Classes (weight, mode):
  lookup     40 single     !m aut-num/route, -x, !r...,o, free text, !i
  origin     20 single     !g / !6 for sampled origins
  setmembers 20 keepalive  !g and !6 for every member AS of the largest
                           AS-sets, as `bgpq4 -L` style clients ask; the
                           members come from `!i<set>,1` on --expand (v4)
  aset        5 keepalive  !a4 / !a6 on the largest AS-sets
  iset        5 keepalive  !i<set>,1 on the largest AS-sets
  session    10 keepalive  bgpq4's sequence: !s-lc, !a4, !s<list>
Output: weight<TAB>class<TAB>mode<TAB>query (loadgen's format).
"""
import argparse
import json
import socket


def whois(addr, q):
    host, port = addr.rsplit(":", 1)
    s = socket.create_connection((host, int(port)), timeout=600)
    s.sendall(q.encode() + b"\n")
    data = b""
    while True:
        c = s.recv(1 << 16)
        if not c:
            break
        data += c
    s.close()
    if data[:1] != b"A":
        return ""
    return data.split(b"\n", 1)[1].rsplit(b"\nC\n", 1)[0].decode()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bindings", required=True)
    ap.add_argument("--expand", required=True)
    ap.add_argument("--sets", type=int, default=5)
    a = ap.parse_args()
    b = json.load(open(a.bindings))
    rows = []

    def add(w, cls, mode, q):
        rows.append(f"{w}\t{cls}\t{mode}\t{q}")

    for r in b.get("route4", []) + b.get("route6", []):
        add(4, "lookup", "single", f"!mroute{'6' if ':' in r['prefix'] else ''},{r['prefix']}{r['origin']}")
        add(4, "lookup", "single", f"-x {r['prefix']}")
        add(4, "lookup", "single", f"!r{r['prefix']},o")
    for x in b.get("aut_num", []):
        add(4, "lookup", "single", f"!maut-num,{x}")
        add(2, "lookup", "single", x)
    for x in b.get("as_set", []):
        add(2, "lookup", "single", f"!i{x}")
    for x in b.get("origin4", []):
        add(4, "origin", "single", f"!g{x}")
    for x in b.get("origin6", []):
        add(2, "origin", "single", f"!6{x}")
    large = b.get("as_set_large", [])[: a.sets]
    members = []
    for s in large:
        ans = whois(a.expand, f"!i{s},1")
        members += [m for m in ans.split() if m.upper().startswith("AS") and m[2:].isdigit()]
    for m in sorted(set(members)):
        add(1, "setmembers", "keepalive", f"!g{m} ;; !6{m}")
    for s in large:
        add(10, "aset", "keepalive", f"!a4{s}")
        add(5, "aset", "keepalive", f"!a6{s}")
        add(10, "iset", "keepalive", f"!i{s},1")
        add(20, "session", "keepalive", f"!s-lc ;; !a4{s} ;; !s{','.join(b.get('source', []))}")
    # Scale weights so classes get the stated shares.
    share = {"lookup": 40, "origin": 20, "setmembers": 20, "aset": 5, "iset": 5, "session": 10}
    tot = {}
    for r in rows:
        w, c = r.split("\t")[:2]
        tot[c] = tot.get(c, 0) + int(w)
    print("# generated by bench/mix.py; weight<TAB>class<TAB>mode<TAB>query")
    for r in rows:
        w, c, rest = r.split("\t", 2)
        print(f"{max(1, round(int(w) * share[c] * 1000 / tot[c]))}\t{c}\t{rest}")


if __name__ == "__main__":
    main()
