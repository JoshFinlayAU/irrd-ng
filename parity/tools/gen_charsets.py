#!/usr/bin/env python3
"""Generate crates/auth/src/charsets.rs: Python's single-byte codecs.

    python3 -I parity/tools/gen_charsets.py > crates/auth/src/charsets.rs

Every codec in Python's `encodings` package that is a 256-entry charmap
(cp1252, iso8859_15, koi8_r, mac_roman and so on), with its decoding table
and every alias `encodings.aliases` gives it, so e-mail bodies in these
charsets decode exactly as v4 decodes them. Undefined bytes are U+FFFE, as
in Python's tables, and are what the error handler sees.
"""
import encodings
import encodings.aliases
import importlib
import pkgutil
import sys

SKIP = {"latin_1", "ascii", "utf_8"}  # handled in email_parser.rs


def main():
    codecs = {}
    for m in sorted(pkgutil.iter_modules(encodings.__path__), key=lambda m: m.name):
        if m.name in SKIP:
            continue
        try:
            mod = importlib.import_module("encodings." + m.name)
        except Exception:
            continue
        table = getattr(mod, "decoding_table", None)
        if isinstance(table, str) and len(table) == 256 and all(ord(c) < 0x10000 for c in table):
            codecs[m.name] = table
    aliases = {}
    for alias, target in encodings.aliases.aliases.items():
        if target in codecs:
            aliases[alias] = target
    for name in codecs:
        aliases[name] = name
    w = sys.stdout.write
    w(f"//! Python {sys.version_info.major}.{sys.version_info.minor}'s single-byte codecs, for `bytes.decode()`.\n")
    w("//! Generated by `parity/tools/gen_charsets.py`; do not edit.\n\n")
    w("/// An undefined byte in a table.\n")
    w("pub(crate) const UNDEFINED: u16 = 0xfffe;\n\n")
    for name, table in codecs.items():
        w(f"const {name.upper()}: [u16; 256] = [\n")
        for i in range(0, 256, 16):
            w("    " + ", ".join(f"0x{ord(c):04x}" for c in table[i:i + 16]) + ",\n")
        w("];\n\n")
    w("/// The table for a normalised codec name or alias.\n")
    w("pub(crate) fn table(name: &str) -> Option<&'static [u16; 256]> {\n")
    w("    Some(match name {\n")
    by_target = {}
    for alias, target in sorted(aliases.items()):
        by_target.setdefault(target, []).append(alias)
    for target in codecs:
        pats = " | ".join(f'"{a}"' for a in sorted(by_target[target]))
        w(f"        {pats} => &{target.upper()},\n")
    w("        _ => return None,\n")
    w("    })\n")
    w("}\n")


if __name__ == "__main__":
    main()
