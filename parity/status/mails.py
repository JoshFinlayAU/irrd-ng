#!/usr/bin/env python3
"""Collect and compare the mails captured by Mailpit.

    mails.py dump OUT.json [--api http://127.0.0.1:9025]   # save, then delete all
    mails.py compare V4.json NG.json

dump keeps each message's raw headers (minus what Mailpit itself adds) and
body. The hostname in v4's footer ("Generated by IRRd version ... on HOST")
is masked: it is the machine's name. compare checks the two sets of mails
are the same. v4 sends them in an order that depends on Python set order,
and lists the objects inside a notification in set order too, so mails are
compared as a set and the objects in each RPKI notification as a set; any
other difference is reported.
"""
import json
import re
import sys
import urllib.request

RULE = "~" * 52


def get(api, path, method="GET"):
    req = urllib.request.Request(api + path, method=method)
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def normalise(raw):
    raw = raw.replace("\r\n", "\n")
    head, _, body = raw.partition("\n\n")
    headers = [h for h in re.split(r"\n(?![ \t])", head) if not re.match(r"(?i)(received|return-path|x-mailpit|message-id|date):", h)]
    body = re.sub(r"(Generated by IRRd version \S+ on ).*$", r"\1<host>", body)
    parts = body.split(RULE)
    objects = None
    if len(parts) == 3:
        objects = sorted(o for o in parts[1].strip("\n").split("\n\n") if o)
        body = parts[0] + RULE + "\n<objects>\n" + RULE + parts[2]
    return {"headers": headers, "body": body, "objects": objects}


def dump(out, api):
    data = json.loads(get(api, "/api/v1/messages?limit=1000"))
    mails = []
    for m in data.get("messages", []):
        raw = get(api, f"/api/v1/message/{m['ID']}/raw").decode("utf-8", "replace")
        mails.append(normalise(raw))
    get(api, "/api/v1/messages", method="DELETE")
    mails.sort(key=lambda m: json.dumps(m, sort_keys=True))
    json.dump(mails, open(out, "w"), indent=1, sort_keys=True)
    print(f"{len(mails)} mails")


def compare(a, b):
    x, y = json.load(open(a)), json.load(open(b))
    if x == y:
        print(f"mails: {len(x)} identical (as a set)")
        return 0
    print(f"mails: DIFFER, {len(x)} vs {len(y)}")
    xs = {json.dumps(m, sort_keys=True) for m in x}
    ys = {json.dumps(m, sort_keys=True) for m in y}
    for m in sorted(xs - ys)[:3]:
        print(f"  v4 only: {m[:1500]}")
    for m in sorted(ys - xs)[:3]:
        print(f"  ng only: {m[:1500]}")
    return 1


if __name__ == "__main__":
    if sys.argv[1] == "dump":
        api = sys.argv[sys.argv.index("--api") + 1] if "--api" in sys.argv else "http://127.0.0.1:9025"
        dump(sys.argv[2], api)
    elif sys.argv[1] == "compare":
        sys.exit(compare(sys.argv[2], sys.argv[3]))
    else:
        sys.exit("mails.py dump OUT | compare A B")
